export const EXTRA_URL_PREFIX = "extra:";
const BY_INDEX = new Map(EXTRA_SPELLS.map((s) => [s.index, s]));

export const EXTRA_EFFECT_CODES: ReadonlyMap<string, string> = new Map(EXTRA_SPELLS.map((s) => [s.index, s.effects]));

export function aliasesFor(index: string): string[] {
  return SPELL_ALIASES[index] ?? [];
}

/** Lets the extra spells sit in the same search list as the ones from the API. */
export const EXTRA_SUMMARIES: SpellSummary[] = EXTRA_SPELLS.map((s) => ({
  index: s.index,
  name: s.name,
  level: s.level,
  url: EXTRA_URL_PREFIX + s.index,
}));

/** A full spell in the same shape the API returns, marked as a summary so the card can say so. */
export function extraSpell(index: string): Spell | null {
  const s = BY_INDEX.get(index);
  if (!s) return null;
  return {
    index: s.index,
    name: s.name,
    level: s.level,
    school: { name: s.school },
    casting_time: s.casting_time,
    range: s.range,
    components: s.components,
    ...(s.material ? { material: s.material } : {}),
    duration: s.duration,
    concentration: s.concentration,
    ritual: s.ritual,
    description: s.summary,
    ...(s.higher_level ? { higher_level: s.higher_level } : {}),
    classes: s.classes.map((name) => ({ name })),
    source: s.source,
    summary: true,
  };
}
